def load_bio_body():
    text = (DATA / "bio.md").read_text(encoding="utf-8")
    # Strip front-matter if present
    if text.startswith("---"):
        parts = text.split("---", 2)
        if len(parts) >= 3:
            text = parts[2]
    return text.strip()


def gen_bio():
    body = load_bio_body()
    return (
        "\n"
        '        <p class="profile-bio">\n'
        "          " + md_inline(body).replace("\n", "\n          ") + "\n"
        "        </p>\n"
        "        "
    )


def gen_training_screen(training):
    lines = []
    for e in training["entries"]:
        sub_parts = [p for p in (e.get("teachers", ""), e.get("school", "")) if p]
        sub = " &middot; ".join(esc(p) for p in sub_parts)
        lines.append(
            '          <li><span class="label">'
            + esc(e["title"])
            + '</span><span class="sub">'
            + sub
            + "</span></li>"
        )
    return (
        "\n      <div class=\"panel col-6\">\n"
        "        <h4>Education / Training</h4>\n"
        "        <ul>\n"
        + "\n".join(lines)
        + "\n        </ul>\n"
        "      </div>\n      "
    )


