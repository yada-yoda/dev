SECTION_SELECTORS = {
    "about":           "#about",
    "profile_bio":     ".profile-bio",
    "profile_gallery": ".headshot-gallery",
    "profile_socials": ".socials",
    "resume":          "#resume",
    "credits":         "#credits",
    "reel":            "#reel-wrapper",
    "contact":         "#contact",
}


def gen_section_visibility(site):
    """Emit a <style> block with display:none rules for any section
    toggled off in site.yml. Renders in <head> so it applies before
    body paints - zero flicker."""
    sections = site.get("sections") or {}
    hidden_rules = []
    for key, selector in SECTION_SELECTORS.items():
        if sections.get(key, True) is False:
            hidden_rules.append(f"{selector}{{display:none!important}}")
    if not hidden_rules:
        return "\n<!-- all sections visible -->\n"
    return "\n<style>" + "".join(hidden_rules) + "</style>\n"


def gen_footer(site):
    f = site.get("footer", {})
    template = f.get("text", "© {{year}} Rizzo.cc")
    show_version = f.get("show_version", True)

    # Replace {{year}} with the dynamic year span (filled by JS at runtime)
    rendered = esc(template).replace("{{year}}", '<span id="yr"></span>')

    # Append version chip if enabled (replaces {{version}} if present, else
    # appends as the next visible element)
    if show_version:
        version_html = f'<span class="ver">{esc(SITE_VERSION)}</span>'
        if "{{version}}" in rendered:
            rendered = rendered.replace("{{version}}", version_html)
        else:
            rendered = rendered.rstrip() + " " + version_html
    else:
        rendered = rendered.replace("{{version}}", "")

    return f"\n<footer>\n  {rendered}\n</footer>\n"


