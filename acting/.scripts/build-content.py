def load_bio_body():
    text = (DATA / "bio.md").read_text(encoding="utf-8")
    # Strip front-matter if present
    if text.startswith("---"):
        parts = text.split("---", 2)
        if len(parts) >= 3:
            text = parts[2]
    return text.strip()


