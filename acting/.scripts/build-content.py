# ---------- helpers ----------

def esc(s):
    """HTML-escape a value safely. Returns empty string for None."""
    if s is None:
        return ""
    return html_lib.escape(str(s), quote=False)


def md_inline(s):
    """Tiny markdown subset for the bio: **bold** and *italic*."""
    s = esc(s)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"\*(.+?)\*", r"<em>\1</em>", s)
    return s


def replace_block(html, marker, new_inner):
    """Replace content between <!-- EDIT: marker [...] --> and
    <!-- /EDIT: marker -->. The marker comments themselves are preserved.
    The EDIT comment may span multiple lines and contain `>` chars in
    its description, so the opening-comment match uses .*? rather than
    [^>]* and the whole pattern runs with DOTALL."""
    pattern = re.compile(
        r"(<!--\s*EDIT:\s*" + re.escape(marker) + r"\b.*?-->)"
        r"(.*?)"
        r"(<!--\s*/EDIT:\s*" + re.escape(marker) + r"\s*-->)",
        re.DOTALL,
    )
    if not pattern.search(html):
        raise SystemExit(f"Marker not found in index.html: EDIT: {marker}")
    return pattern.sub(
        lambda m: m.group(1) + new_inner + m.group(3),
        html,
        count=1,
    )


