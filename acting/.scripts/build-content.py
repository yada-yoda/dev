    s = site["seo"]
    return (
        f'\n<title>{esc(s["title"])}</title>\n'
        f'<meta name="description" content="{esc(s["description"])}">\n'
        f'<meta name="author" content="{esc(s["author"])}">\n'
        f'<meta name="theme-color" content="#2c2e3d">\n'
        f'<meta name="robots" content="{esc(s["robots"])}">\n'
        f'<link rel="canonical" href="{esc(s["canonical_url"])}">\n'
    )


