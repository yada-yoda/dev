def _load_list(path):
    """Load a YAML file shaped like `entries: [...]` and return that list.
    Returns [] if the file is missing or empty."""
    if not path.exists():
        return []
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return data.get("entries", []) or []


def main():
    # Credits are split into four files: film.yml, tv.yml, theater.yml,
    # commercial.yml. The Decap Credits collection exposes each as a
    # separate entry. tab_visibility lives in site.yml under credits_tabs.
    site = yaml.safe_load((DATA / "site.yml").read_text(encoding="utf-8"))
    credits = {
        "film": _load_list(DATA / "film.yml"),
        "tv": _load_list(DATA / "tv.yml"),
        "theater": _load_list(DATA / "theater.yml"),
        "commercial": _load_list(DATA / "commercial.yml"),
        "tab_visibility": site.get("credits_tabs") or {},
    }
    training = yaml.safe_load((DATA / "training.yml").read_text(encoding="utf-8"))
    hero = yaml.safe_load((DATA / "hero.yml").read_text(encoding="utf-8"))
    about = yaml.safe_load((DATA / "about.yml").read_text(encoding="utf-8"))
    panels = yaml.safe_load((DATA / "panels.yml").read_text(encoding="utf-8"))
    contact = yaml.safe_load((DATA / "contact.yml").read_text(encoding="utf-8"))
    html = INDEX.read_text(encoding="utf-8")

    # Head: SEO meta, OG, GA4
    html = replace_block(html, "site-meta", gen_site_meta(site))
    html = replace_block(html, "og-tags", gen_og_tags(site))
    html = replace_block(html, "ga4", gen_ga4(site))

    # Chrome: top-nav menu + footer + section visibility
    html = replace_block(html, "menu", gen_menu(site))
    html = replace_block(html, "footer", gen_footer(site))
    html = replace_block(html, "section-visibility", gen_section_visibility(site))

    # Bio + Credits + Training
    html = replace_block(html, "bio", gen_bio())
    html = replace_block(html, "training", gen_training_screen(training))
    html = replace_block(html, "print-training", gen_training_print(training))
    # Tabs strip — only includes visible tabs; first visible gets active state
    html = replace_block(html, "credits-tabs", gen_credits_tabs(credits))

    # Per-tab panels: render only when the tab is visible. The build script's
    # replace_block fills with empty content so the panel <div> disappears.
    def panel_or_hidden(slug, gen, *args):
        visible_slugs = {s for s, _ in _visible_tabs(credits)}
        if slug not in visible_slugs:
            return "\n    "
        return gen(*args, is_active=_is_first_visible(credits, slug))

    html = replace_block(html, "film-credits",
                         panel_or_hidden("film", gen_film_screen, credits["film"]))
    html = replace_block(html, "tv-credits",
                         panel_or_hidden("tv", gen_tv_screen, credits["tv"]))
    html = replace_block(html, "theater-credits",
                         panel_or_hidden("theater", gen_theater_screen, credits["theater"]))
    html = replace_block(html, "commercial-credits",
                         panel_or_hidden("commercial", gen_commercial_screen, credits.get("commercial", [])))

    # Printed PDF resume always uses all sections except Commercial
    # (Commercial is intentionally omitted from print).
    html = replace_block(html, "print-film-credits", gen_film_print(credits["film"]))
    html = replace_block(html, "print-tv-credits", gen_tv_print(credits["tv"]))
    html = replace_block(html, "print-theater-credits", gen_theater_print(credits["theater"]))

    # Hero
    html = replace_block(html, "hero-slides", gen_hero_slides(hero))
    html = replace_block(html, "hero-quotes", gen_hero_quotes(hero))

    # About
    html = replace_block(html, "rizzo-definition", gen_definition(about))
    html = replace_block(html, "pull-quote", gen_pull_quote(about))

    # Resume panels
    html = replace_block(html, "physical", gen_physical(panels["physical"]))
    html = replace_block(html, "languages", gen_languages(panels["languages"]))
    html = replace_block(html, "print-languages", gen_languages_print(panels["languages"]))
    html = replace_block(html, "measurements", gen_measurements(panels["measurements"]))
    html = replace_block(html, "licensing", gen_licensing(panels["licensing"]))
    html = replace_block(html, "print-licensing", gen_licensing_print(panels["licensing"]))
    html = replace_block(html, "skills", gen_skills(panels["skills"]))
    html = replace_block(html, "print-skills", gen_skills_print(panels["skills"]))
    html = replace_block(html, "favorite-films", gen_favorite_films(panels["favorite_films"]))
    html = replace_block(html, "inspirations", gen_inspirations(panels["inspirations"]))
    html = replace_block(html, "print-stats", gen_print_stats(panels))

